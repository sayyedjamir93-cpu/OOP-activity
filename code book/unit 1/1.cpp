#include <iostream> // iostream is used for input/output.
using namespace std;
int main()
{
    int roll = 101;                      // int stores whole numbers.
    char grade = 'A';                    // char stores one character.
    float fee = 12500.50;                // float stores decimal numbers.
    cout << "Roll No: " << roll << endl; // cout displays values.
    cout << "Grade: " << grade << endl;
    cout << "Fee: " << fee << endl;
    return 0; // return 0 ends the program.
}